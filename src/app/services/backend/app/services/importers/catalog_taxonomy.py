# Типы решений, осмысленные для производственных/сервисных площадок вне
# трёх базовых объектов, — они не участвуют в подборе, но остаются в каталоге.
NON_TARGET_TYPE_CODES = {"rpa_software", "other"}


def _norm(text: str | None) -> str:
    if not text:
        return ""
    return text.lower().replace("ё", "е").strip()


def detect_solution_type(*texts: str | None) -> str:
    """Определяет тип решения по подтипу/названию/описанию позиции каталога."""
    # Сначала пробуем самый специфичный источник — «Подтип» из файла организатора.
    for text in texts:
        haystack = _norm(text)
        if not haystack:
            continue
        for st in SOLUTION_TYPES:
            if any(kw in haystack for kw in st.keywords):
                return st.code
    return "other"


def detect_processes(scenario: str | None, *extra: str | None) -> list[tuple[str, str]]:
    """Сценарий из файла организатора → список (тип объекта, код процесса).

    Сценарий может содержать несколько процессов через запятую
    (например, «Мониторинг, Патрулирование, Перевозка грузов»), поэтому
    проверяем каждое его предложение отдельно и не размножаем совпадения.
    """
    raw = scenario or ""
    for extra_text in extra:
        if extra_text:
            raw = f"{raw} {extra_text}"
    haystack = _norm(raw)
    if not haystack:
        return []

    found: list[tuple[str, str]] = []
    for chunk in haystack.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        for proc in PROCESSES:
            if any(kw in chunk for kw in proc.keywords):
                pair = (proc.object_type, proc.code)
                if pair not in found:
                    found.append(pair)
    return found


def process_name(object_type: str, process_code: str) -> str:
    for proc in PROCESSES:
        if proc.object_type == object_type and proc.code == process_code:
            return proc.name
    return process_code


def metric_code_for(object_type: str, process_code: str) -> str | None:
    for proc in PROCESSES:
        if proc.object_type == object_type and proc.code == process_code:
            return proc.metric_code
    return None
